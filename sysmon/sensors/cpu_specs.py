def lookup_cpu_specs(name: str, fallback_base: Optional[float] = None) -> Tuple[Optional[float], Optional[float]]:
    """Look up factory base and max boost clock speeds (in MHz) for a given CPU name.

    Returns ``(base_mhz, max_boost_mhz)``. If a value cannot be determined, returns
    ``(fallback_base, None)``.
    """
    if not name:
        return (fallback_base, None)

    norm = re.sub(r"[^a-z0-9]", "", name.lower())

    # Try AMD models
    for key, (b, boost) in _AMD_SPECS.items():
        if key in norm:
            base = fallback_base if fallback_base else b
            return (base, boost)

    # Try Intel models (e.g. i7-13700K -> "13700k")
    for key, (b, boost) in _INTEL_SPECS.items():
        if key in norm:
            base = fallback_base if fallback_base else b
            return (base, boost)

    # Check for "@ X.XXGHz" in the name string
    match = re.search(r"@\s*([\d\.]+)\s*GHz", name, re.IGNORECASE)
    if match:
        try:
            ghz = float(match.group(1))
            mhz = ghz * 1000.0
            return (fallback_base or mhz, None)
        except ValueError:
            pass

    return (fallback_base, None)
